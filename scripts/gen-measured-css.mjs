#!/usr/bin/env node
// Generate src/styles/measured.css from the per-node component tokens of docs/design/tokens.json
// (written by scripts/measure/extract-tokens.mjs). One rule per node key:
//   .<comp>-<key> { <css-prop>: <light value>; ... }
// plus a `prefers-color-scheme: dark` block with the values that differ in the dark dumps.
// The values are copied from tokens.json (never typed here); writing them out literally instead
// of through custom properties keeps the webview from carrying ~40 000 inherited variables
// (docs/99, F8-T2).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'docs/design/tokens.json'), 'utf8'));
const kebab = (s) => s.replace(/_/g, '-').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const CSS_PROP = { rect_w: null, rect_h: null }; // rects are informational only
const isMeta = (k) => k === 'name' || k.startsWith('source') || /(^|_)note$/.test(k) || k.startsWith('_');
const isThemed = (v) => v && typeof v === 'object' && !Array.isArray(v) && 'light' in v && 'dark' in v;

let css = '/* GENERATED by scripts/gen-measured-css.mjs from docs/design/tokens.json. Do not edit. */\n';
let dark = '';
let rules = 0;
for (const [comp, group] of Object.entries(tokens.component || {})) {
  if (!group || typeof group !== 'object') continue;
  for (const [key, props] of Object.entries(group)) {
    if (isMeta(key) || !props || typeof props !== 'object') continue;
    const light = [];
    const darkDecls = [];
    for (const [p, v] of Object.entries(props)) {
      if (v === null || v === undefined) continue;
      if (p in CSS_PROP && CSS_PROP[p] === null) continue;
      const cssProp = kebab(p);
      if (isThemed(v)) {
        light.push(`  ${cssProp}: ${v.light};`);
        darkDecls.push(`    ${cssProp}: ${v.dark};`);
      } else {
        light.push(`  ${cssProp}: ${Array.isArray(v) ? v.join(' ') : v};`);
      }
    }
    if (light.length) {
      css += `.${kebab(comp)}-${kebab(key)} {\n${light.join('\n')}\n}\n`;
      rules++;
    }
    if (darkDecls.length) dark += `  .${kebab(comp)}-${kebab(key)} {\n${darkDecls.join('\n')}\n  }\n`;
  }
}
if (dark) css += `@media (prefers-color-scheme: dark) {\n${dark}}\n`;
writeFileSync(resolve(root, 'src/styles/measured.css'), css);
console.log(`wrote src/styles/measured.css: ${rules} rules`);

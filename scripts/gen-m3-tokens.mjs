#!/usr/bin/env node
// Generate the Material 3 design tokens of the app from docs/design/m3/theme.json
// (docs/11-material3.md section 3):
//   src/styles/tokens.css   --md-ref-typeface-*, --md-sys-color-* (light in :root, dark under
//                           prefers-color-scheme: dark), --md-sys-typescale-*, --md-sys-shape-*,
//                           --md-sys-motion-*, --md-sys-elevation-level<n>, --md-sys-state-*,
//                           --md-icon-font, --ugc-space-*, --ugc-layout-*, --ugc-motion-*
//   src/styles/layout.ts    LAYOUT (the layout tokens as strings) + layoutNumber()
//   src/styles/motion.ts    MOTION (the app motion tokens with --md-sys-motion names resolved)
//   src/styles/palette.ts   COLOR_MAP (stored hex -> M3 custom color roles per theme),
//                           EVENT_COLORS, EVENT_COLOR_NAMES, LOCAL_CALENDAR_DEFAULT
// The color scheme is computed with @material/material-color-utilities from `color.seed`
// (TonalSpot, contrast 0); nothing here is typed by hand. Set UGC_TOKENS_OUT=<dir> to write
// somewhere else (used by scripts/check-m3.sh to verify the committed files are current).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  Hct,
  MaterialDynamicColors,
  SchemeContent,
  SchemeFidelity,
  SchemeTonalSpot,
  SchemeVibrant,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = process.env.UGC_TOKENS_OUT ? resolve(process.env.UGC_TOKENS_OUT) : resolve(root, 'src/styles');
const theme = JSON.parse(readFileSync(resolve(root, 'docs/design/m3/theme.json'), 'utf8'));

const isMeta = (k) => k.startsWith('_') || k === 'source' || /(^|_)source$/.test(k) || /(^|_)note$/.test(k);
const kebab = (s) => s.replace(/_/g, '-').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const HEADER_CSS = '/* GENERATED by scripts/gen-m3-tokens.mjs from docs/design/m3/theme.json. Do not edit. */\n';
const HEADER_TS = '// GENERATED by scripts/gen-m3-tokens.mjs from docs/design/m3/theme.json. Do not edit.\n';

// ---------------------------------------------------------------- color scheme (generated)
// Every dynamic color role material-web components and our stylesheets read. The list follows
// MaterialDynamicColors; a role missing in the installed library version is skipped and reported.
const COLOR_ROLES = [
  'background', 'onBackground', 'surface', 'surfaceDim', 'surfaceBright', 'surfaceContainerLowest',
  'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'onSurface', 'surfaceVariant', 'onSurfaceVariant', 'inverseSurface', 'inverseOnSurface', 'outline',
  'outlineVariant', 'shadow', 'scrim', 'surfaceTint', 'primary', 'onPrimary', 'primaryContainer',
  'onPrimaryContainer', 'inversePrimary', 'secondary', 'onSecondary', 'secondaryContainer',
  'onSecondaryContainer', 'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer', 'error',
  'onError', 'errorContainer', 'onErrorContainer', 'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed',
  'onPrimaryFixedVariant', 'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed',
  'onSecondaryFixedVariant', 'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
];
const VARIANTS = { tonalSpot: SchemeTonalSpot, vibrant: SchemeVibrant, fidelity: SchemeFidelity, content: SchemeContent };
const Scheme = VARIANTS[theme.color.variant];
if (!Scheme) throw new Error(`theme.color.variant ${theme.color.variant} is not one of ${Object.keys(VARIANTS).join(', ')}`);
const seed = Hct.fromInt(argbFromHex(theme.color.seed));
const contrast = Number(theme.color.contrast_level ?? 0);
const schemeFor = (dark) => new Scheme(seed, dark, contrast);
const missingRoles = [];
function colorRoles(dark) {
  const scheme = schemeFor(dark);
  const out = [];
  for (const role of COLOR_ROLES) {
    const dc = MaterialDynamicColors[role];
    if (!dc) { if (!dark) missingRoles.push(role); continue; }
    out.push([`--md-sys-color-${kebab(role)}`, hexFromArgb(dc.getArgb(scheme))]);
  }
  return out;
}

// ---------------------------------------------------------------- static system tokens
const typeface = [];
for (const [k, v] of Object.entries(theme.typeface)) {
  if (isMeta(k) || k === 'icons') continue;
  typeface.push([`--md-ref-typeface-${kebab(k)}`, v]);
}
typeface.push(['--md-icon-font', theme.typeface.icons]);

const typescale = [];
for (const [role, t] of Object.entries(theme.typescale)) {
  if (isMeta(role)) continue;
  typescale.push([`--md-sys-typescale-${role}-font`, `var(--md-ref-typeface-${t.font})`]);
  typescale.push([`--md-sys-typescale-${role}-size`, t.size]);
  typescale.push([`--md-sys-typescale-${role}-line-height`, t.line_height]);
  typescale.push([`--md-sys-typescale-${role}-weight`, t.weight]);
  typescale.push([`--md-sys-typescale-${role}-tracking`, t.tracking]);
}

const shape = Object.entries(theme.shape).filter(([k]) => !isMeta(k)).map(([k, v]) => [`--md-sys-shape-${k}`, v]);
const motion = Object.entries(theme.motion).filter(([k]) => !isMeta(k)).map(([k, v]) => [`--md-sys-motion-${k}`, v]);
const state = Object.entries(theme.state).filter(([k]) => !isMeta(k)).map(([k, v]) => [`--md-sys-state-${k}`, v]);

const elevation = [];
const shadowAt = (alpha) => `color-mix(in srgb, var(--md-sys-color-shadow) ${Math.round(Number(alpha) * 100)}%, transparent)`;
for (const [level, v] of Object.entries(theme.elevation)) {
  if (isMeta(level) || level === 'key_alpha' || level === 'ambient_alpha') continue;
  const value = v === 'none' ? 'none' : `${v.key} ${shadowAt(theme.elevation.key_alpha)}, ${v.ambient} ${shadowAt(theme.elevation.ambient_alpha)}`;
  elevation.push([`--md-sys-elevation-${level}`, value]);
}

const space = Object.entries(theme.space).filter(([k]) => !isMeta(k)).map(([k, v]) => [`--ugc-space-${k}`, v]);
const layoutEntries = Object.entries(theme.layout).filter(([k]) => !isMeta(k));
const layout = layoutEntries.map(([k, v]) => [`--ugc-layout-${kebab(k)}`, v]);

const motionNames = new Set(Object.keys(theme.motion).filter((k) => !isMeta(k)));
const appMotionEntries = Object.entries(theme.app_motion).filter(([k]) => !isMeta(k));
const appMotion = appMotionEntries.map(([k, v]) => [`--ugc-motion-${kebab(k)}`, motionNames.has(v) ? `var(--md-sys-motion-${v})` : v]);

// ---------------------------------------------------------------- tokens.css
const decl = (list, indent) => list.map(([n, v]) => `${indent}${n}: ${v};`).join('\n');
const light = [...typeface, ...colorRoles(false), ...typescale, ...shape, ...motion, ...elevation, ...state, ...space, ...layout, ...appMotion];
const dark = colorRoles(true);
let css = HEADER_CSS;
css += `:root {\n${decl(light, '  ')}\n}\n`;
css += `@media (prefers-color-scheme: dark) {\n  :root {\n${decl(dark, '    ')}\n  }\n}\n`;

// ---------------------------------------------------------------- typescale.css
// One utility class per role, like material-web's md-typescale-styles, so components apply a
// role with a class instead of repeating five declarations.
let typescaleCss = HEADER_CSS;
for (const [role, t] of Object.entries(theme.typescale)) {
  if (isMeta(role)) continue;
  typescaleCss += `.md-typescale-${role} {\n  font-family: var(--md-sys-typescale-${role}-font);\n  font-size: var(--md-sys-typescale-${role}-size);\n  line-height: var(--md-sys-typescale-${role}-line-height);\n  font-weight: var(--md-sys-typescale-${role}-weight);\n  letter-spacing: var(--md-sys-typescale-${role}-tracking);\n}\n`;
  void t;
}

// ---------------------------------------------------------------- layout.ts / motion.ts
let layoutTs = HEADER_TS;
layoutTs += `export const LAYOUT = {\n${layoutEntries.map(([k, v]) => `  ${k}: ${JSON.stringify(String(v))},`).join('\n')}\n} as const;\n`;
layoutTs += `\n/** Numeric part of a layout token ("48px" → 48, "1.7" → 1.7). */\nexport const layoutNumber = (v: string): number => parseFloat(v);\n`;

let motionTs = HEADER_TS;
motionTs += `export const MOTION = {\n${appMotionEntries.map(([k, v]) => `  ${k}: ${JSON.stringify(String(motionNames.has(v) ? theme.motion[v] : v))},`).join('\n')}\n} as const;\n`;

// ---------------------------------------------------------------- palette.ts
// M3 custom colors (https://m3.material.io/styles/color/advanced/define-new-colors): a tonal
// palette with the hue and chroma of the stored colour; light = tones 40 / 90 / 10, dark =
// tones 80 / 30 / 90 for color / container / on-container. Built from TonalPalette directly
// instead of customColor(): that helper raises the chroma to 48, which turns Google's greys
// (#616161, #c2c2c2) cyan.
const entries = new Map();
const addCustom = (hex) => {
  const key = hex.toLowerCase();
  if (entries.has(key)) return;
  const hct = Hct.fromInt(argbFromHex(key));
  const palette = TonalPalette.fromHueAndChroma(hct.hue, hct.chroma);
  const tone = (t) => hexFromArgb(palette.tone(t));
  entries.set(key, {
    light: { color: tone(40), container: tone(90), onContainer: tone(10) },
    dark: { color: tone(80), container: tone(30), onContainer: tone(90) },
  });
};
for (const hex of theme.color.custom_colors.calendar_classic) addCustom(hex);
for (const { hex } of Object.values(theme.color.custom_colors.event_modern)) addCustom(hex);
addCustom(theme.color.custom_colors.local_calendar_default);

let paletteTs = HEADER_TS;
paletteTs += `export interface ChipColors {\n  /** Chip border and calendar dot. */\n  color: string;\n  /** Chip background. */\n  container: string;\n  /** Chip text. */\n  onContainer: string;\n}\n\n`;
paletteTs += `/** Stored hex (classic calendar colour from the API or modern event colour) → M3 custom color roles per theme. */\n`;
paletteTs += `export const COLOR_MAP: Record<string, { light: ChipColors; dark: ChipColors }> = {\n${[...entries].map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}\n};\n`;
paletteTs += `\n/** Event colorId → modern hex (the value the backend stores). */\nexport const EVENT_COLORS: Record<string, string> = {\n${Object.entries(theme.color.custom_colors.event_modern).map(([id, c]) => `  ${JSON.stringify(id)}: ${JSON.stringify(c.hex.toLowerCase())},`).join('\n')}\n};\n`;
paletteTs += `\n/** Event colorId → Google's colour name. */\nexport const EVENT_COLOR_NAMES: Record<string, string> = {\n${Object.entries(theme.color.custom_colors.event_modern).map(([id, c]) => `  ${JSON.stringify(id)}: ${JSON.stringify(c.name)},`).join('\n')}\n};\n`;
paletteTs += `\nexport const LOCAL_CALENDAR_DEFAULT = ${JSON.stringify(theme.color.custom_colors.local_calendar_default.toLowerCase())};\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, 'tokens.css'), css);
writeFileSync(resolve(outDir, 'typescale.css'), typescaleCss);
writeFileSync(resolve(outDir, 'layout.ts'), layoutTs);
writeFileSync(resolve(outDir, 'motion.ts'), motionTs);
writeFileSync(resolve(outDir, 'palette.ts'), paletteTs);
console.log(`wrote ${outDir}/tokens.css (${light.length} light tokens, ${dark.length} dark), layout.ts (${layoutEntries.length}), motion.ts (${appMotionEntries.length}), palette.ts (${entries.size} colours)`);
if (missingRoles.length) console.log(`skipped color roles missing in this material-color-utilities version: ${missingRoles.join(', ')}`);
